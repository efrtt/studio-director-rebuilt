// The jump palette's catalogue: every destination the four menu pages link to.
//
// Ctrl-K has to work on the calendar, on a family's editor, on a report — pages
// that carry no menu of their own. The only place this build knows the app's
// destinations from is the crawl, so `tools/build-destinations.mjs` reads
// data/pages.json once and writes `src/lib/destinations.js`. Nothing here is
// student data: a code (`ManageRegFeeRules`), a label, and which menu it is on.
//
// Regenerate after a crawl:
//
//   node tools/build-destinations.mjs
//
// A destination whose shape needs a value (`CustomReport(report_id)`) is left
// out: it cannot be opened without one, and a palette entry that goes nowhere is
// worse than an absent one.

import fs from 'node:fs';
import path from 'node:path';

const here = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'));
const root = path.resolve(here, '..');

// The page code, and the name the page gives itself. `AdminHome` and `ReportsHome`
// are the app's own ids; the titles are what the reader prints as the heading.
const MENUS = [
  { code: 'AdminHome', menu: 'Settings' },
  { code: 'ReportsHome', menu: 'Reports' },
  { code: 'ChargesHome', menu: 'Charges & Payments' },
  { code: 'EmailTextHome', menu: 'Communications' }
];

// `HomePage` is the nav link every menu repeats. It is not a destination of the
// page it appears on, and the palette already carries the rail's own links.
const SKIP = new Set(['HomePage']);

function pageName(href) {
  try {
    return new URL(href, 'http://x/').searchParams.get('page') || '';
  } catch (err) {
    return '';
  }
}

// `ManageRegFeeRules` -> `Manage reg fee rules`, `SSOOnOff` -> `SSO on off`.
// The app prints these pages with their own wording, which the crawl does not
// keep for links nobody followed; the code is the best name available for them,
// and the palette searches it as well as the label.
export function humanise(code) {
  const spaced = String(code)
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1 $2')
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .replace(/[_-]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  return spaced.charAt(0).toUpperCase() + spaced.slice(1).toLowerCase().replace(/\b([a-z])/g, (m) => m);
}

function labelOf(code) {
  const text = humanise(code);
  // Keep the first letter's case, lowercase the rest, as the reader would.
  return text.charAt(0).toUpperCase() + text.slice(1);
}

// One entry per page: the crawl can visit the same URL twice (a link followed
// with and without `clicktab`), and the copy with the most links is the menu.
function menuPage(pages, code) {
  const matching = pages.filter((p) => pageName(p.url) === code && p.linkShapes);
  if (!matching.length) return null;
  return matching.sort((a, b) => Object.keys(b.linkShapes).length - Object.keys(a.linkShapes).length)[0];
}

export function buildDestinations(pages) {
  const out = [];
  const seen = new Set();

  for (const { code: pageCode, menu } of MENUS) {
    const page = menuPage(pages, pageCode);
    if (!page) continue;
    for (const shape of Object.keys(page.linkShapes)) {
      if (SKIP.has(shape)) continue;
      // A shape with parameters is a form of its own, not a destination.
      if (!/^[A-Za-z0-9_]+$/.test(shape)) continue;
      if (seen.has(shape)) continue;
      seen.add(shape);
      out.push({ code: shape, label: labelOf(shape), menu });
    }
  }

  return out;
}

function main() {
  const data = JSON.parse(fs.readFileSync(path.join(root, 'data/pages.json'), 'utf8'));
  const list = buildDestinations(data.pages || []);

  const body = list.map((d) =>
    '  { code: ' + JSON.stringify(d.code) + ', label: ' + JSON.stringify(d.label)
    + ', menu: ' + JSON.stringify(d.menu) + ' }').join(',\n');

  const file = '// Generated by tools/build-destinations.mjs from data/pages.json.\n'
    + '// Do not edit by hand: run the tool, then `npm run golden`.\n'
    + '//\n'
    + '// ' + list.length + ' destinations across the four menu pages. Codes are the\n'
    + '// app\\u2019s own page names, so they double as search keywords.\n'
    + 'export const DESTINATIONS = [\n' + body + '\n];\n';

  fs.writeFileSync(path.join(root, 'src/lib/destinations.js'), file);
  console.log('wrote src/lib/destinations.js: ' + list.length + ' destinations');
}

if (process.argv[1] && process.argv[1].replace(/\\/g, '/').endsWith('build-destinations.mjs')) main();
