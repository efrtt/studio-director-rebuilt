// ==UserScript==
// @name         Studio Director - rebuilt week + records
// @namespace    local.sd.rebuilt
// @version      __SD_VERSION__
// @updateURL    __SD_UPDATE_URL__
// @downloadURL  __SD_DOWNLOAD_URL__
// @description  Rebuilt week calendar and record lists for The Studio Director. Reads the app's own pages with your existing session; never writes data and never handles credentials.
// @author       you
// @match        https://app.thestudiodirector.com/*/*
// @run-at       document-idle
// @noframes
// @grant        none
// ==/UserScript==

/*
 * A rebuilt reading surface for The Studio Director.
 *
 * The page shapes, all taken from live dumps and one crawl of 447 screens:
 *   1. the week calendar      table.TimeBlock (page=CalendarPage)
 *   2. a record list          #idSearchSpan .searchResultList
 *   3. a record editor         table.Form + a#save (or tabs): the form and its
 *                              tab panels, saved through the app's own Save
 *   4. a report                filters + #runreport, run through the app
 *   5. a form with an action   settings, letters, compose-mail: the app's own
 *                              control is what is pressed
 *   6. a table screen          dashboards, list-ish settings, print sheets:
 *                              read-only, filterable, printable
 *   7. a tile index            the five rail menus, as a searchable grid
 *
 * Anything else is left to the original app, one click away.
 *
 * SAFETY
 *   - Zero writes of its own: no POST, no form submission, no token handling.
 *     Saves and runs press the app's own controls, so the app builds the request.
 *   - At most one same-origin GET per page view, with credentials: same-origin — and
 *     none at all when the live page already answers the read.
 *   - Esc, the Original button, or #original all return to the app's own page.
 *
 * The block between the bundle markers is generated by tools/build-userscript.mjs.
 */

(function () {
  'use strict';

  /* ---- generated bundle (dist/sd.js) ---- */
  /*__SD_BUNDLE__*/
  /* ---- end generated bundle ---- */

  var app = typeof SD !== 'undefined' ? SD : null;
  if (!app || typeof app.autoMount !== 'function') {
    console.warn('[sd] bundle missing - leaving the original page alone');
    return;
  }

  var ORIGINAL = '#original';
  var LOGIN_STYLE = 'sd-login';
  var instance = null;

  function wantsOriginal() {
    return location.hash === ORIGINAL;
  }

  // Never replace the sign-in screen: that is where the session is created.
  function isLoginPage() {
    var form = document.querySelector('form#idForm');
    if (form && /login\.sd/i.test(form.getAttribute('action') || '')) return true;
    return !!document.querySelector('.LoginContainer');
  }

  function showOriginal() {
    if (instance) {
      try { instance.destroy(); } catch (err) { console.warn('[sd] teardown', err); }
      instance = null;
    }
    if (location.hash === ORIGINAL) history.replaceState(null, '', location.pathname + location.search);
  }

  // The sign-in page is never rebuilt or replaced: it is where the session is
  // made, so the app's own form stays exactly as it is. A stylesheet cannot
  // change what that form sends, so this one page is skinned with colour only —
  // same markup, same controls, same submit.
  function skinLogin() {
    if (!app.loginCss) return;
    // The choice saved in the header's Colour scheme button travels here: same
    // key, same attribute, so the sign-in does not need a switch of its own.
    if (app.applyLoginTheme) app.applyLoginTheme(document.documentElement);
    if (document.getElementById(LOGIN_STYLE)) return;
    var el = document.createElement('style');
    el.id = LOGIN_STYLE;
    el.textContent = app.loginCss;
    (document.head || document.documentElement).appendChild(el);
  }

  async function start() {
    if (wantsOriginal()) return;
    if (isLoginPage()) { skinLogin(); return; }
    if (document.getElementById('sd-root')) return;
    try {
      instance = await app.autoMount({
        onOriginal: function () { location.hash = ORIGINAL; }
      });
    } catch (err) {
      // A view that throws must not leave a blank shell over the app. Drop what
      // was mounted and let the app's own page show — the same state Esc gives.
      // (The drop question did exactly this: an empty root, no way back.)
      console.error('[sd] mount failed', err);
      if (instance) {
        try { instance.destroy(); } catch (e) { console.warn('[sd] teardown', e); }
        instance = null;
      }
      var root = document.getElementById('sd-root');
      if (root && root.parentNode) root.parentNode.removeChild(root);
    }
  }

  window.addEventListener('hashchange', function () {
    if (wantsOriginal()) showOriginal();
    else if (!document.getElementById('sd-root')) start();
  });

  start();
})();
