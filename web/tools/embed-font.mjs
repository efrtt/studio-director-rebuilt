#!/usr/bin/env node
// Embeds the Nunito face the Island theme asks for as a data: URI.
//
// The userscript has to stay one offline artefact: nothing may be fetched at
// runtime, and a machine that never installed Nunito still has to render the
// rounded look, so the face travels inside the stylesheet the theme ships.
// That is the same trick src/fonts.css plays with Open Sans, kept in a separate
// file because only this one theme wants Nunito - the base stylesheet must not
// carry it, or `main` (which has no extra theme) would pay for it too.
//
// The raw .woff2 lives beside the licence in src/fonts/, so this script needs no
// network and the sheet can be rebuilt byte for byte:
//
//   node tools/embed-font.mjs           write src/acnh-fonts.css
//   node tools/embed-font.mjs --check   fail if the committed sheet is stale
//
// A test (test/font.test.mjs) decodes each data: URI and compares it to that
// .woff2, so the sheet cannot be hand-edited into a different font.
//
// Latin subset only. Every other script falls through to the fallback stack
// rather than downloading a face the theme will never show.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');

const OUT = join(root, 'src/acnh-fonts.css');

// The Latin range Google Fonts serves, which is the same one src/fonts.css
// declares for Open Sans: covers Latin-1 plus the punctuation and symbols the
// admin screens actually print (ellipsis, arrows, euro, minus, no-break space).
const LATIN =
  'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, ' +
  'U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, ' +
  'U+2212, U+2215, U+FEFF, U+FFFD';

// One variable face covering 200-1000 rather than three static cuts: the theme
// sets body copy at 700 and headings at 800/900, and one file costs less than
// two statics would.
const FACES = [
  {
    family: 'Nunito',
    style: 'normal',
    weight: '200 1000',
    file: 'src/fonts/nunito-latin-var.woff2',
  },
];

const NOTICE = `/* Nunito, embedded rather than fetched. Generated by web/tools/embed-font.mjs.
 *
 * SIL Open Font License 1.1 - Copyright 2014 The Nunito Project Authors
 * (https://github.com/googlefonts/nunito). The full licence is beside the font
 * in fonts/OFL-nunito.txt; it has to travel with the font, which is why this
 * notice is in the stylesheet that ships rather than only in the repository.
 *
 * Latin subset only, as a single variable face (wght 200-1000): the Island theme
 * sets every control in a bolder weight, so one file covers body, labels and
 * headings at once. A data: URI keeps the userscript one offline artefact with
 * nothing to fetch, so the type is the same on a machine that has never
 * installed the font.
 */
`;

function base64Of(face) {
  const path = join(root, face.file);
  if (!existsSync(path)) {
    throw new Error(`missing font file: ${relative(root, path)}`);
  }
  const bytes = readFileSync(path);
  // wOF2: a truncated or HTML error page would otherwise be embedded as
  // base64 and only fail at paint time, in a browser, silently.
  if (bytes.length < 4 || bytes.subarray(0, 4).toString('latin1') !== 'wOF2') {
    throw new Error(`${face.file} is not a woff2 file (bad magic)`);
  }
  return { base64: bytes.toString('base64'), bytes: bytes.length };
}

function block(face) {
  const { base64, bytes } = base64Of(face);
  return (
    `/* ${face.family} ${face.weight}, latin, ${bytes} bytes of woff2 */\n` +
    '@font-face {\n' +
    `  font-family: '${face.family}';\n` +
    `  font-style: ${face.style};\n` +
    `  font-weight: ${face.weight};\n` +
    '  font-display: swap;\n' +
    `  src: url(data:font/woff2;base64,${base64}) format('woff2');\n` +
    `  unicode-range: ${LATIN};\n` +
    '}\n'
  );
}

function build() {
  const faces = FACES.map(block).join('\n');
  const bytes = FACES.reduce((n, f) => n + base64Of(f).bytes, 0);
  return { css: `${NOTICE}${faces}`, bytes };
}

const { css, bytes } = build();
const check = process.argv.includes('--check');
const existing = existsSync(OUT) ? readFileSync(OUT, 'utf8') : null;

if (check) {
  if (existing === css) {
    console.log(`font sheet is current (${(css.length / 1024).toFixed(1)} KiB of CSS from ${bytes} bytes of woff2)`);
    process.exit(0);
  }
  console.error(
    `font sheet is stale: run \`node tools/embed-font.mjs\` (src/acnh-fonts.css, ${existing === null ? 'missing' : `${existing.length} bytes`})`,
  );
  process.exit(1);
}

writeFileSync(OUT, css);
console.log(
  `wrote ${relative(root, OUT)} (${(css.length / 1024).toFixed(1)} KiB, from ${bytes} bytes of woff2)`,
);
